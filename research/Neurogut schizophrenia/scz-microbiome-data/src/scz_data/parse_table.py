"""FR-1: parse GutMIND Table S1 and write config/studies.yaml."""

from __future__ import annotations

import re

import openpyxl
import yaml

from scz_data.settings import Settings

ARCHIVE_RULES = [
    (re.compile(r"^PRJ(EB|NA|DB)\d+$"), "ENA"),
    (re.compile(r"^CRA\d+$"), "GSA"),
    (re.compile(r"^CNP\d+$"), "CNGB"),
]


def infer_archive(accession: str) -> str:
    """Accession prefix -> archive (PRD FR-1). Anything unrecognised is 'manual'."""
    acc = (accession or "").strip()
    for pattern, archive in ARCHIVE_RULES:
        if pattern.match(acc):
            return archive
    return "manual"


def read_table_s1(path, sheet: str) -> list[dict]:
    ws = openpyxl.load_workbook(path, data_only=True)[sheet]
    rows = list(ws.iter_rows(values_only=True))
    # The PRD says row 3, the file actually has it on row 2: locate it instead of hard-coding.
    header_idx = next(i for i, r in enumerate(rows) if r and r[0] == "StudyID")
    header = [h for h in rows[header_idx] if h is not None]
    records = []
    for r in rows[header_idx + 1:]:
        if not r or r[0] is None:
            continue
        records.append(dict(zip(header, r[: len(header)])))
    return records


def _int(x) -> int:
    return int(round(float(x)))


def build_studies(records: list[dict], abbreviation: str, overrides: dict) -> list[dict]:
    studies = []
    for rec in records:
        if rec.get("Abbreviation") != abbreviation:
            continue
        sid = rec["StudyID"]
        accession = str(rec["Project"]).strip()
        ov = dict(overrides.get(sid, {}))
        accessions = ov.pop("accessions", [accession])
        archive = "manual" if ov.pop("manual", False) else infer_archive(accession)
        study = {
            "study_id": sid,
            "accession": accession,
            "accessions": accessions,
            "archive": archive,
            "country": rec["Country"],
            "platform": rec["Platform"],
            "disease": rec["Disease"],
            "cohort_type": rec["CohortType"],
            "diagnosis_criteria": rec["Clinical Accessment"],  # sic: column name in Table S1
            "expected": {
                "healthy_raw": _int(rec["HealthCount"]),
                "scz_raw": _int(rec["DiseaseCount"]),
                "healthy_filtered": _int(rec["HealthCount_Filtered"]),
                "scz_filtered": _int(rec["DiseaseCount_Filtered"]),
                "total_filtered": _int(rec["TotalCount_Filtered"]),
            },
            "disease_only": bool(ov.pop("disease_only", False)),
        }
        study.update(ov)
        studies.append(study)
    return studies


def run(settings: Settings) -> list[dict]:
    cfg = settings.cfg
    records = read_table_s1(settings.path("table_s1"), cfg["table_s1"]["sheet"])
    studies = build_studies(records, cfg["table_s1"]["abbreviation"], cfg.get("study_overrides", {}))
    out = settings.path("studies")
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("# GENERATED by `python -m scz_data config` from data/sTable1.xlsx + config.yaml study_overrides.\n")
        fh.write("# Do not edit by hand.\n")
        yaml.safe_dump({"studies": studies}, fh, sort_keys=False, allow_unicode=True)
    print(f"[config] wrote {out.relative_to(settings.root)}: {len(studies)} {cfg['table_s1']['abbreviation']} studies")
    return studies
