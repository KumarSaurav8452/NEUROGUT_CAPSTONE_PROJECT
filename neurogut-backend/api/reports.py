"""
NEUROGUT -- Report API
========================
Generate and download clinical PDF reports.
"""

import uuid
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session

from db.database import get_db
from db.models import User, Prediction, Report, MicrobiomeSample, Patient
from api.auth import get_current_user
from schemas.patient import ReportGenerateRequest, ReportResponse
from services.pdf_generator import generate_report_pdf
from services.storage import storage_service

router = APIRouter(prefix="/api/reports", tags=["Reports"])


@router.post("/generate", response_model=ReportResponse)
def generate_report(
    req: ReportGenerateRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
):
    """Generate a PDF clinical report for a prediction."""
    pred = db.query(Prediction).filter(Prediction.id == req.prediction_id).first()
    if not pred:
        raise HTTPException(status_code=404, detail="Prediction not found")

    # Check if report already exists
    existing = db.query(Report).filter(Report.prediction_id == pred.id).first()
    if existing:
        return existing

    # Get associated sample and patient info
    sample = db.query(MicrobiomeSample).filter(MicrobiomeSample.id == pred.sample_id).first()
    patient_info = {"patient_code": "N/A", "age": None, "sex": "N/A", "notes": ""}
    sample_data = {"collection_date": "N/A", "input_method": "N/A"}

    if sample:
        sample_data = {
            "collection_date": sample.collection_date,
            "input_method": sample.input_method,
        }
        patient = db.query(Patient).filter(Patient.id == sample.patient_id).first()
        if patient:
            patient_info = {
                "patient_code": patient.patient_code,
                "age": patient.age,
                "sex": patient.sex,
                "notes": patient.notes,
            }

    prediction_data = {
        "depression_prob": pred.depression_prob,
        "anxiety_prob": pred.anxiety_prob,
        "depression_label": pred.depression_label,
        "anxiety_label": pred.anxiety_label,
        "risk_tier": pred.risk_tier,
        "rf_importances": pred.rf_importances_json or {},
        "xgb_importances": pred.xgb_importances_json or {},
        "consensus_features": pred.consensus_features_json or [],
        "model_version": pred.model_version,
    }

    # Generate PDF
    pdf_bytes = generate_report_pdf(patient_info, prediction_data, sample_data)

    # Save to storage
    file_key = f"report_{pred.id}.pdf"
    file_path = storage_service.save(file_key, pdf_bytes)

    # Save report record
    report = Report(
        id=str(uuid.uuid4()),
        prediction_id=pred.id,
        generated_by=user.id,
        file_path=file_path,
        file_key=file_key,
        report_version=1,
    )
    db.add(report)
    db.commit()
    db.refresh(report)
    return report


@router.get("/{report_id}/download")
def download_report(
    report_id: str,
    token: str | None = None,
    db: Session = Depends(get_db),
):
    """Download a generated PDF report.

    Supports auth via:
    - Authorization: Bearer <token> header (standard)
    - ?token=<jwt> query param (for browser window.open / direct links)
    """
    from api.auth import decode_token

    # Authenticate via query param or header
    if token:
        payload = decode_token(token)
        user_id = payload.get("sub")
        if not user_id:
            raise HTTPException(status_code=401, detail="Invalid token")
    else:
        # Try header-based auth via dependency injection manually
        from fastapi import Request
        raise HTTPException(
            status_code=401,
            detail="Token required. Pass ?token=<jwt> or Authorization header.",
        )

    report = db.query(Report).filter(Report.id == report_id).first()
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")

    if not storage_service.exists(report.file_key):
        raise HTTPException(status_code=404, detail="Report file not found on disk")

    return FileResponse(
        path=report.file_path,
        media_type="application/pdf",
        filename=f"neurogut_report_{report.prediction_id[:8]}.pdf",
    )


@router.get("/", response_model=list[ReportResponse])
def list_reports(
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
):
    """List all reports generated by the current user's hospital."""
    reports = db.query(Report).filter(
        Report.generated_by.in_(
            db.query(User.id).filter(User.hospital_id == user.hospital_id)
        )
    ).order_by(Report.created_at.desc()).all()
    return reports
